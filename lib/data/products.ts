function buildSpecifications(product: Product): ProductSpecifications {
  return {
    metalPurity: metalPurity[product.metal],
    metalWeight: product.category === "Bracelets" ? "8.50 g" : product.category === "Necklaces" ? "6.20 g" : "3.40 g",
    gemstoneWeight: product.gemstone === "Pearl" ? "7.00 mm" : "1.00 ct",
    gemstoneQuality: product.gemstone === "Diamond" ? "VS1, F-G" : "AAA Grade",
    setting: product.category === "Engagement Rings" ? "Prong Setting" : "Secure Classic Setting",
    certification: "IGI Certified & Hallmarked",
  };
}

function enrichProduct(product: Product): Product {
  const isRing = product.category === "Rings" || product.category === "Engagement Rings";
  const images = buildImages(product);
  const rating = 4.7 + (Number(product.id.replace("p", "")) % 4) * 0.1;
  const reviewCount = 18 + (Number(product.id.replace("p", "")) % 20) * 3;
  return {
    ...product,
    images,
    rating: Math.min(5, Number(rating.toFixed(1))),
    reviewCount,
    reviews: buildReviews(product),
    specifications: buildSpecifications(product),
    availableMetals: ["Yellow Gold", "White Gold", "Rose Gold", "Platinum"],
    availableGemstones: ["Diamond", "Emerald", "Ruby", "Sapphire", "Pearl"],
    gemstoneSizes: [...defaultGemstoneSizes],
    ringSizes: isRing ? [...defaultRingSizes] : undefined,
    optionPricing: {
      metals: { ...metalDelta },
      gemstones: { ...gemstoneDelta },
      gemstoneSizes: { ...gemstoneSizeDelta },
    },
    shippingInfo: "Complimentary insured shipping across India. Orders are dispatched within 2-4 business days, with secure premium packaging.",
    returnPolicy: "Enjoy a 15-day return window for unworn items in original condition, with complimentary return pickup and quality inspection.",
  };
}

export const products: Product[] = baseProducts.map(enrichProduct);
export const enrichedProducts = products;

export function getProductBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getRelatedProducts(product: Product, limit = 4) {
  return products
    .filter((item) => item.id !== product.id && (item.category === product.category || item.gemstone === product.gemstone))
    .slice(0, limit);
}