function buildImages(product: Product): string[] {
  const pool = [
    product.image,
    product.hoverImage,
    "/images/references/1.jpg",
    "/images/references/2.jpg",
    "/images/references/3.jpg",
    "/images/references/4.jpg",
  ];
  return [...new Set(pool)].slice(0, 4);
}

